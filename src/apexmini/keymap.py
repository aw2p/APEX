USAGE_TO_NAME = {v: k.upper() for k, v in NAME_TO_USAGE.items()}
USAGE_TO_NAME[0xFB] = "LOGO"


def usage_for_name(name):
    return NAME_TO_USAGE[name.casefold()]


def name_for_usage(usage):
    return USAGE_TO_NAME.get(usage, "UNKN_%02X" % usage)
